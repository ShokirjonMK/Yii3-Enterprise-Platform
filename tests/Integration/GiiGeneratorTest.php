<?php

declare(strict_types=1);

namespace App\Tests\Integration;

use App\Platform\Gii\EnterpriseGii;
use App\Platform\Gii\PathGuard;
use App\Platform\Gii\PlannedFile;
use App\Platform\Gii\Spec\FieldSpecParser;
use App\Platform\Gii\Spec\GiiSpecException;
use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

/**
 * Enterprise Gii end to end against a TEMPORARY root (never the real src/): full module generation,
 * `php -l` of every generated PHP file, dry-run writes nothing, idempotent re-run, overwrite protection,
 * explicit overwrite, path safety and input validation.
 */
final class GiiGeneratorTest extends IntegrationTestCase
{
    private const FIELDS = 'title:string:required:max=255,amount:decimal:min=0,status:enum(draft|active|closed),due_on:date,owner_id:user';
    private const HEADER = 'Generated by Yii3 Enterprise Platform · Enterprise Gii — author ShokirjonMK';

    private string $root;
    private EnterpriseGii $gii;

    protected function setUp(): void
    {
        parent::setUp();
        if (!EnterpriseGii::isInstalled()) {
            self::markTestSkipped('yiisoft/yii-gii (dev dependency) is not installed.');
        }
        $this->root = sys_get_temp_dir() . '/gii-' . bin2hex(random_bytes(6));
        mkdir($this->root . '/migrations', 0777, true);
        // a copy of the route directories so NN numbering is computed like in the real tree
        foreach (['config/routes/admin', 'config/routes/api-v1', 'config/routes/web'] as $dir) {
            mkdir($this->root . '/' . $dir, 0777, true);
            foreach (glob(dirname(__DIR__, 2) . '/' . $dir . '/*.php') ?: [] as $file) {
                if (!str_contains(basename($file), 'contracts')) {
                    copy($file, $this->root . '/' . $dir . '/' . basename($file));
                }
            }
        }
        $this->gii = $this->get(EnterpriseGii::class)->withRoot($this->root);
    }

    protected function tearDown(): void
    {
        if (isset($this->root) && is_dir($this->root)) {
            $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($this->root, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
            foreach ($it as $f) {
                $f->isDir() ? rmdir($f->getPathname()) : unlink($f->getPathname());
            }
            rmdir($this->root);
        }
        parent::tearDown();
    }

    public function testDryRunWritesNothingAndListsEveryFile(): void
    {
        $before = $this->tree();
        $plan = $this->gii->plan('Contracts', self::FIELDS);
        self::assertSame($before, $this->tree(), 'dry run must not write');
        self::assertSame(array_keys(EnterpriseGii::GENERATORS), $plan->generators);
        self::assertSame(count($plan->files), $plan->counts()['new']);
        $paths = $plan->paths();
        foreach ([
            'src/Modules/Contracts/module.php',
            'src/Modules/Contracts/Domain/Contract.php',
            'src/Modules/Contracts/Domain/ContractStatus.php',
            'src/Modules/Contracts/Domain/ContractRules.php',
            'src/Modules/Contracts/Domain/ContractEvent.php',
            'src/Modules/Contracts/Application/ContractService.php',
            'src/Modules/Contracts/Application/ContractWorkflow.php',
            'src/Modules/Contracts/Application/ContractNotifier.php',
            'src/Modules/Contracts/Infrastructure/ContractRepository.php',
            'src/Modules/Contracts/Infrastructure/ContractActivityProjector.php',
            'src/Modules/Contracts/Infrastructure/PurgeDeletedContractsJob.php',
            'src/Modules/Contracts/Infrastructure/GenerateContractsReportJob.php',
            'src/Modules/Contracts/Infrastructure/ContractsConnector.php',
            'src/Admin/Action/Contracts/ContractsController.php',
            'src/Web/Action/Contracts/ContractsController.php',
            'src/Api/V1/Action/Contracts/ContractsController.php',
            'resources/views/admin/contracts/index.php',
            'resources/views/admin/contracts/form.php',
            'resources/views/admin/contracts/view.php',
            'resources/views/admin/contracts/_fields.php',
            'resources/views/web/contracts/index.php',
            'config/routes/admin/23b-contracts.php',
            'config/routes/web/contracts.php',
            'config/routes/api-v1/31-contracts.php',
            'config/common/permissions/contracts.php',
            'config/common/jobs/contracts.php',
            'config/common/events/contracts.php',
            'config/common/di/contracts.php',
            'tests/Unit/ContractsDomainTest.php',
            'tests/Integration/ContractsServiceTest.php',
            'tests/Api/ApiContractsTest.php',
            'tests/E2E/ContractsUiTest.php',
        ] as $expected) {
            self::assertContains($expected, $paths, $expected);
        }
        $migrations = array_values(array_filter($paths, static fn($p) => str_starts_with($p, 'migrations/')));
        self::assertCount(7, $migrations);
        foreach (['Contracts', 'ContractsEvents', 'ContractsReports', 'ContractsWorkflow', 'ContractsNotifications', 'ContractsIntegration', 'ContractsSchedule'] as $suffix) {
            self::assertCount(1, preg_grep('#^migrations/M\d{12}' . $suffix . '\.php$#', $migrations), $suffix);
        }
    }

    public function testApplyWritesValidPhpWithHeaderAndIsIdempotent(): void
    {
        $plan = $this->gii->apply($this->gii->plan('Contracts', self::FIELDS));
        self::assertFalse($plan->hasErrors());
        foreach ($plan->files as $f) {
            self::assertSame('created', $f->result, $f->path());
            $abs = $this->root . '/' . $f->path();
            self::assertFileExists($abs);
            $code = (string) file_get_contents($abs);
            self::assertStringStartsWith("<?php\n\n/**\n * " . self::HEADER, $code, $f->path());
            exec('php -l ' . escapeshellarg($abs) . ' 2>&1', $out, $exit);
            self::assertSame(0, $exit, $f->path() . ': ' . implode("\n", $out));
        }
        // no stray files outside the plan
        $expected = $plan->paths();
        sort($expected);
        self::assertSame($expected, $this->tree());

        $again = $this->gii->plan('Contracts', self::FIELDS);
        self::assertSame(count($again->files), $again->counts()['unchanged'], 'second run: everything unchanged');
        self::assertSame($plan->paths(), $again->paths(), 'stable file names (migration timestamps, route numbers)');
    }

    public function testOverwriteProtectionAndExplicitOverwrite(): void
    {
        $this->gii->apply($this->gii->plan('Contracts', self::FIELDS));
        $rel = 'src/Modules/Contracts/Domain/ContractRules.php';
        $abs = $this->root . '/' . $rel;
        $original = (string) file_get_contents($abs);
        file_put_contents($abs, $original . "\n// local change\n");

        $plan = $this->gii->plan('Contracts', self::FIELDS);
        $file = $plan->file($rel);
        self::assertNotNull($file);
        self::assertSame(PlannedFile::SKIP, $file->status);
        self::assertStringContainsString('-// local change', $file->diff(), 'unified diff from yii-gii CodeFile');
        $this->gii->apply($plan);
        self::assertStringContainsString('// local change', (string) file_get_contents($abs), 'protected file untouched');
        self::assertSame('skipped', $file->result);

        $plan = $this->gii->plan('Contracts', self::FIELDS, 'all', [$rel]);
        self::assertSame(PlannedFile::OVERWRITE, $plan->file($rel)?->status);
        $this->gii->apply($plan);
        self::assertSame($original, file_get_contents($abs));
        self::assertSame('overwrote', $plan->file($rel)?->result);

        // overwrite paths must belong to the generation
        $this->expectException(GiiSpecException::class);
        $this->gii->plan('Contracts', self::FIELDS, 'all', ['config/common/params.php']);
    }

    public function testSubsetResolvesDependenciesAndKeepsFeatureSwitches(): void
    {
        self::assertSame(['entity', 'crud', 'rbac', 'api'], $this->gii->resolve('api'));
        self::assertSame(['entity', 'job', 'scheduler'], $this->gii->resolve('scheduler'));
        $plan = $this->gii->plan('Invoices', 'number:string:required:unique:max=32,total:decimal,paid:bool', 'crud,api');
        self::assertNotContains('workflow', $plan->generators);
        self::assertNull($plan->file('src/Modules/Invoices/Application/InvoiceWorkflow.php'));
        self::assertNotNull($plan->file('src/Api/V1/Action/Invoices/InvoicesController.php'));
        $service = $plan->file('src/Modules/Invoices/Application/InvoiceService.php')?->content() ?? '';
        self::assertStringNotContainsString('Outbox', $service, 'no Kafka event generator → no outbox dependency');
        $this->gii->apply($plan);
        foreach ($plan->files as $f) {
            exec('php -l ' . escapeshellarg($this->root . '/' . $f->path()) . ' 2>&1', $out, $exit);
            self::assertSame(0, $exit, $f->path());
        }
    }

    public function testInputValidationAndPathSafety(): void
    {
        foreach (['contracts', 'Ab', '../Evil', 'Con tracts', 'Projects', str_repeat('A', 42)] as $bad) {
            try {
                $this->gii->plan($bad, self::FIELDS);
                self::fail("module name \"$bad\" accepted");
            } catch (GiiSpecException $e) {
                self::assertArrayHasKey('module', $e->errors(), $bad);
            }
        }
        foreach (['', 'id:string', 'title:strin', 'Title:string', 'a:enum()', 'x1:string:max=abc', 'status:string', 'flag:bool:unique', 'title:string,title:text'] as $bad) {
            try {
                FieldSpecParser::parse($bad);
                self::fail("field spec \"$bad\" accepted");
            } catch (GiiSpecException) {
            }
        }
        try {
            $this->gii->plan('Contracts', self::FIELDS, 'crud,bogus');
            self::fail('unknown generator accepted');
        } catch (GiiSpecException $e) {
            self::assertArrayHasKey('generators', $e->errors());
        }
        foreach (['../etc/passwd.php', 'src/Platform/Access/AccessService.php', 'config/common/params.php', '/abs/x.php',
            'src/Modules/Projects/module.php', 'src/Admin/Action/DevTools/X.php', 'src/Modules/X/a b.php', 'src/Modules/X/y.txt'] as $bad) {
            try {
                PathGuard::resolve($this->root, $bad);
                self::fail("unsafe path \"$bad\" accepted");
            } catch (GiiSpecException) {
            }
        }
        // a symlinked directory leading out of the root is refused
        mkdir($this->root . '/src/Modules', 0777, true);
        @symlink(sys_get_temp_dir(), $this->root . '/src/Modules/Evil');
        if (is_link($this->root . '/src/Modules/Evil')) {
            try {
                PathGuard::resolve($this->root, 'src/Modules/Evil/x.php');
                self::fail('symlink escape accepted');
            } catch (GiiSpecException) {
            }
            unlink($this->root . '/src/Modules/Evil');
        }
        self::assertSame($this->root . '/src/Modules/Contracts/module.php', PathGuard::resolve($this->root, 'src/Modules/Contracts/module.php'));
    }

    /** @return list<string> relative paths of all files under the temp root */
    private function tree(): array
    {
        $out = [];
        $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($this->root, FilesystemIterator::SKIP_DOTS));
        foreach ($it as $f) {
            if ($f->isFile()) {
                $rel = substr($f->getPathname(), strlen($this->root) + 1);
                if (!str_starts_with($rel, 'config/routes/') || str_contains($rel, 'contracts')) {
                    $out[] = $rel;
                }
            }
        }
        sort($out);
        return $out;
    }
}
