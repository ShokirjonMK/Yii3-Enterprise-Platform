<?php

declare(strict_types=1);

namespace App\Admin\Kafka;

use App\Platform\Messaging\Kafka\KafkaConfig;

/**
 * Renders the idempotent topic provisioning script from `kafka_topics` registry rows — the same output as
 * `./yii kafka:provision` (src/Console/Command/KafkaProvisionCommand.php), so the admin UI and the CLI agree.
 */
final class KafkaProvisioningScript
{
    public function __construct(private readonly KafkaConfig $config) {}

    /** @param list<array<string,mixed>> $rows registry rows (KafkaAdmin::topicDrift()) */
    public function render(array $rows, ?int $replicationFactor = null): string
    {
        $lines = ['#!/bin/sh', '# Generated by ./yii kafka:provision — idempotent', 'set -e', 'BS="${KAFKA_BOOTSTRAP:-' . $this->config->brokers . '}"'];
        foreach ($rows as $r) {
            $lines[] = sprintf(
                '/opt/kafka/bin/kafka-topics.sh --bootstrap-server "$BS" --create --if-not-exists --topic %s --partitions %d --replication-factor %d --config retention.ms=%d --config cleanup.policy=%s',
                escapeshellarg($this->config->topic((string) $r['name'])),
                (int) $r['partitions'],
                (int) ($replicationFactor ?? $r['replication_factor']),
                (int) $r['retention_ms'],
                escapeshellarg((string) $r['cleanup_policy']),
            );
        }
        return implode("\n", $lines) . "\n";
    }
}
