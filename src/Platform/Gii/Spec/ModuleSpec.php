<?php

declare(strict_types=1);

namespace App\Platform\Gii\Spec;

use DateTimeImmutable;
use Yiisoft\Strings\Inflector;

/**
 * Everything the templates need to know about the module being generated: names derived from the
 * module name (namespace, entity, table, permission/route prefixes), the fields, the enabled
 * features (generators) and stable file names (migration timestamps and route-file numbers are
 * re-used when the files already exist, so a re-run is idempotent).
 */
final class ModuleSpec
{
    public const NAME = '/^[A-Z][A-Za-z0-9]{2,40}$/';

    /** Names that would collide with platform sections / routes / the reference module. */
    public const RESERVED = [
        'Projects', 'Users', 'Tenants', 'Rbac', 'Roles', 'Permissions', 'Api', 'Integrations', 'Notifications', 'Workflow',
        'Workflows', 'Jobs', 'Kafka', 'Postgres', 'Redis', 'Storage', 'Infrastructure', 'Deployments', 'Monitoring',
        'Security', 'Backups', 'Audit', 'Settings', 'Devtools', 'DevTools', 'Modules', 'Incidents', 'Auth', 'Dashboard',
        'Account', 'Home', 'Login', 'Logout', 'Health', 'Push', 'Static', 'Admin', 'Web', 'Platform', 'Shared', 'Gii',
        'Approvals', 'Schedules', 'Flags', 'Organizations', 'Maintenance', 'Docs', 'Setup', 'Install', 'System', 'Me',
    ];

    public const HEADER = "/**\n * Generated by Yii3 Enterprise Platform · Enterprise Gii — author ShokirjonMK\n */";

    /** Migration suffix (after the module name) => offset in seconds after the base timestamp. */
    private const MIGRATIONS = ['' => 0, 'Events' => 1, 'Reports' => 2, 'Workflow' => 3, 'Notifications' => 4, 'Integration' => 5, 'Schedule' => 6];

    public readonly string $entity;
    public readonly string $code;
    public readonly string $slug;
    public readonly string $entitySnake;
    public readonly string $label;
    public readonly string $entityLabel;
    /** @var array<string,string> suffix => class name */
    private array $migrationClasses = [];

    /**
     * @param list<FieldSpec> $fields
     * @param list<string> $features enabled generator ids
     */
    public function __construct(
        public readonly string $module,
        public readonly array $fields,
        public readonly array $features,
        public readonly string $root,
    ) {
        $inflector = new Inflector();
        $singular = $inflector->toSingular($module);
        $this->entity = $singular === '' ? $module : $singular;
        $this->code = $inflector->pascalCaseToId($module, '_');
        $this->slug = $inflector->pascalCaseToId($module, '-');
        $this->entitySnake = $inflector->pascalCaseToId($this->entity, '_');
        $this->label = ucfirst(str_replace('_', ' ', $this->code));
        $this->entityLabel = ucfirst(str_replace('_', ' ', $this->entitySnake));
        $this->resolveFiles();
    }

    public function has(string $feature): bool
    {
        return in_array($feature, $this->features, true);
    }

    public function statusField(): ?FieldSpec
    {
        foreach ($this->fields as $f) {
            if ($f->isStatus()) {
                return $f;
            }
        }
        return null;
    }

    public function hasStatus(): bool
    {
        return $this->statusField() !== null;
    }

    /** First string-like field: used as the record title (links, notifications, search). */
    public function displayField(): ?FieldSpec
    {
        foreach ($this->fields as $f) {
            if (in_array($f->type, ['string', 'email'], true)) {
                return $f;
            }
        }
        return null;
    }

    /** @return list<FieldSpec> */
    public function editable(): array
    {
        return array_values(array_filter($this->fields, static fn(FieldSpec $f) => !$f->isStatus()));
    }

    /** @return list<FieldSpec> */
    public function ofType(string ...$types): array
    {
        return array_values(array_filter($this->fields, static fn(FieldSpec $f) => in_array($f->type, $types, true)));
    }

    /** @return list<FieldSpec> */
    public function searchable(): array
    {
        return array_values(array_filter($this->fields, static fn(FieldSpec $f) => $f->isSearchable()));
    }

    /** @return list<FieldSpec> */
    public function filterable(): array
    {
        return array_values(array_filter($this->fields, static fn(FieldSpec $f) => $f->isFilterable()));
    }

    /** @return list<FieldSpec> */
    public function unique(): array
    {
        return array_values(array_filter($this->fields, static fn(FieldSpec $f) => $f->unique));
    }

    /** @return list<string> */
    public function permissions(): array
    {
        return array_map(fn(string $p) => $this->code . '.' . $p, ['view', 'create', 'update', 'delete']);
    }

    public function flag(): string
    {
        return 'module.' . $this->code;
    }

    public function topic(): string
    {
        return $this->code . '.events';
    }

    public function consumerGroup(): string
    {
        return $this->slug . '-activity';
    }

    public function reportJob(): string
    {
        return $this->code . '.report.generate';
    }

    public function cleanupJob(): string
    {
        return $this->code . '.cleanup';
    }

    public function workflowCode(): string
    {
        return $this->entitySnake . '.lifecycle';
    }

    public function notifyTemplate(): string
    {
        return $this->entitySnake . ($this->hasStatus() ? '.status_changed' : '.created');
    }

    public function migrationClass(string $suffix = ''): string
    {
        return $this->migrationClasses[$suffix];
    }

    public function migrationPath(string $suffix = ''): string
    {
        return $this->modulePath('migrations/' . $this->migrationClass($suffix) . '.php');
    }

    public function adminRouteFile(): string
    {
        return $this->modulePath('Admin/routes.php');
    }

    public function apiRouteFile(): string
    {
        return $this->modulePath('Api/routes.php');
    }

    public function modulePath(string $rel): string
    {
        return 'src/Modules/' . $this->module . '/' . $rel;
    }

    /** Placeholders available in every template. */
    public function vars(): array
    {
        return [
            '{{HEADER}}' => self::HEADER,
            '{{Module}}' => $this->module,
            '{{Entity}}' => $this->entity,
            '{{entity}}' => lcfirst($this->entity),
            '{{entity_snake}}' => $this->entitySnake,
            '{{code}}' => $this->code,
            '{{slug}}' => $this->slug,
            '{{table}}' => $this->code,
            '{{label}}' => $this->label,
            '{{entityLabel}}' => $this->entityLabel,
            '{{entityLabelLower}}' => mb_strtolower($this->entityLabel),
            '{{labelLower}}' => mb_strtolower($this->label),
            '{{flag}}' => $this->flag(),
            '{{topic}}' => $this->topic(),
        ];
    }

    /** Replaces the module placeholders plus $extra in a template chunk. */
    public function fill(string $template, array $extra = []): string
    {
        return strtr(strtr($template, $extra), $this->vars());
    }

    private function resolveFiles(): void
    {
        // migrations: re-use existing timestamps of this module, otherwise start after the newest migration
        $existing = [];
        $maxTs = '000000000000';
        foreach ([...(glob($this->root . '/migrations/M*.php') ?: []), ...(glob($this->root . '/src/Modules/*/migrations/M*.php') ?: [])] as $file) {
            if (preg_match('/^M(\d{12})([A-Za-z0-9]+)\.php$/', basename($file), $mm)) {
                $existing[$mm[2]] = $mm[1];
                $maxTs = max($maxTs, $mm[1]);
            }
        }
        $base = $existing[$this->module] ?? null;
        if ($base === null) {
            $now = (new DateTimeImmutable('now'))->format('ymdHis');
            $base = $now > $maxTs ? $now : self::addSeconds($maxTs, 1);
        }
        foreach (self::MIGRATIONS as $suffix => $offset) {
            $name = $this->module . $suffix;
            $ts = $existing[$name] ?? self::addSeconds($base, $offset);
            $this->migrationClasses[$suffix] = 'M' . $ts . $name;
        }
    }

    private static function addSeconds(string $ts, int $seconds): string
    {
        $d = DateTimeImmutable::createFromFormat('ymdHis', $ts);
        if ($d === false) {
            return $ts;
        }
        return $d->modify('+' . $seconds . ' seconds')->format('ymdHis');
    }
}
