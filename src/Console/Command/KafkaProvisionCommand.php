<?php

declare(strict_types=1);

namespace App\Console\Command;

use App\Platform\Messaging\Kafka\KafkaAdmin;
use App\Platform\Messaging\Kafka\KafkaConfig;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Yiisoft\Yii\Console\ExitCode;

/**
 * Topic provisioning from the `kafka_topics` registry.
 *
 * php-rdkafka does not expose Kafka's AdminClient, therefore this command renders an idempotent
 * provisioning script for Kafka's official CLI (kafka-topics.sh --if-not-exists), which is executed
 * by the `kafka-init` compose service / a Kubernetes Job (or applied as Strimzi KafkaTopic resources).
 */
#[AsCommand(name: 'kafka:provision', description: 'Render topic provisioning script from the registry / show drift')]
final class KafkaProvisionCommand extends Command
{
    public function __construct(
        private readonly KafkaAdmin $admin,
        private readonly KafkaConfig $config,
    ) {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this->addOption('output', 'o', InputOption::VALUE_REQUIRED, 'Write script to file (default: runtime/kafka-topics.sh)', 'runtime/kafka-topics.sh')
            ->addOption('replication-factor', null, InputOption::VALUE_REQUIRED, 'Override replication factor (e.g. 3 in HA)');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $rows = $this->admin->topicDrift();
        $rf = $input->getOption('replication-factor');
        $lines = ['#!/bin/sh', '# Generated by ./yii kafka:provision — idempotent', 'set -e', 'BS="${KAFKA_BOOTSTRAP:-' . $this->config->brokers . '}"'];
        foreach ($rows as $r) {
            $name = $this->config->topic((string) $r['name']);
            $lines[] = sprintf(
                '/opt/kafka/bin/kafka-topics.sh --bootstrap-server "$BS" --create --if-not-exists --topic %s --partitions %d --replication-factor %d --config retention.ms=%d --config cleanup.policy=%s',
                escapeshellarg($name), (int) $r['partitions'], (int) ($rf ?? $r['replication_factor']), (int) $r['retention_ms'], escapeshellarg((string) $r['cleanup_policy']),
            );
            $state = $r['exists'] === null ? 'unknown (Kafka unreachable)' : ($r['exists'] ? 'exists, partitions=' . $r['live_partitions'] : 'MISSING');
            $output->writeln(sprintf('%-28s %s', $name, $state));
        }
        $file = (string) $input->getOption('output');
        file_put_contents($file, implode("\n", $lines) . "\n");
        @chmod($file, 0755);
        $output->writeln("Script written to $file");
        return ExitCode::OK;
    }
}
